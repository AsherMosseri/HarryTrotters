// Is a pack running? mode is 'on', 'off', or 'auto' (in season).
export function packOn(pack, mode, today, competitionDate) {
  if (mode === 'on') return true;
  if (mode === 'off' || !mode) return false;
  const md = today.slice(5);
  if (pack.from) return pack.from <= pack.to ? md >= pack.from && md <= pack.to : md >= pack.from || md <= pack.to;
  if (pack.competition && competitionDate) {
    const days = (new Date(`${competitionDate}T12:00:00`) - new Date(`${today}T12:00:00`)) / 86400000;
    return days >= 0 && days <= pack.competition;
  }
  return false;
}
