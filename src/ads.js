export const adById = (id) => ADS.find((a) => a.id === id);

// The ad for a slot right now: rotates every 25 seconds, and each slot (the
// banner, the board, the chat) starts at a different place in the list.
export function adFor(ads, slot, now = Date.now()) {
  if (!ads.length) return null;
  const offset = { banner: 0, board: 7, chat: 13, full: 4 }[slot] || 0;
  return ads[(Math.floor(now / 25000) + offset) % ads.length];
}
